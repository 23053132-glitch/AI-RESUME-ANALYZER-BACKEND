const pdfParse = require("pdf-parse")
const { Types } = require("mongoose")
const {generateInterviewReport} = require("../services/ai.service")
const interviewReportModel = require("../models/interviewReport.model")
const Groq = require("groq-sdk");
/**
 * 
 * @description Controller to generate interview report based on user self description,resume and job description.
 */




async function generateInterViewReportController(req,res){
  try {
     if (!req.file) return res.status(400).json({ message: "No resume file uploaded" });
     
     const resumeContent = await pdfParse(req.file.buffer)

     const {selfDescription,jobDescription} = req.body;
     const interViewReportByAi = await generateInterviewReport({
         resume: resumeContent.text,
         selfDescription,
         jobDescription
     })
     
     const interviewReport = await interviewReportModel.create({
         user: req.user.id,
         resume:resumeContent.text,
         selfDescription,
         jobDescription,
         ...interViewReportByAi // destructured
     })
    
     res.status(201).json({
       message:"Interview report generated successful",
       interviewReport
     })
  } catch (error) {
     console.error("Error in generateInterViewReportController:", error);
     res.status(500).json({ message: error.message || "Failed to generate report" });
  }
} 

/**
 * @description Controller to get interview report by interviewId.
 */
async function getInterviewReportByIdController(req,res){
  const { interviewId } = req.params

  // validate id format
  if (!Types.ObjectId.isValid(interviewId)) {
    return res.status(404).json({ message: "Interview report not found." })
  }

  const interviewReport = await interviewReportModel.findOne({ _id: interviewId, user: req.user.id })

  if (!interviewReport) {
    return res.status(404).json({ message: "Interview report not found." })
  }

  return res.status(200).json({ message: "Interview report fetched successfully.", interviewReport })
}

/**
 * @description Controller to get all the reports that are generated by user that is logged in
 * 
 */
async function getAllInterviewReportsController(req, res) {
    const interviewReports = await interviewReportModel.find({ user: req.user.id }).sort({ createdAt: -1 }).select("-resume -selfDescription -jobDescription -__v -technicalQuestions -behavioralQuestions -skillGaps -preparationPlan")

    res.status(200).json({
        message: "Interview reports fetched successfully.",
        interviewReports
    })
}
const voiceQAController = async (req, res) => {
  const { question, resumeText } = req.body;
  try {
    const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });
    const completion = await groq.chat.completions.create({
      model: 'llama-3.3-70b-versatile',
      messages: [
        {
          role: 'system',
          content: `You are a resume advisor. Here is the candidate's interview report:\n\n${resumeText}\n\nGive short, helpful answers in 2-3 sentences max.`
        },
        { role: 'user', content: question }
      ],
      max_tokens: 200
    });
    res.json({ answer: completion.choices[0].message.content });
  } catch (err) {
    console.error('Voice QA error:', err);
    res.status(500).json({ error: err.message });
  }
};
module.exports = { 
  generateInterViewReportController,
  getInterviewReportByIdController,
  getAllInterviewReportsController,
  voiceQAController
};
